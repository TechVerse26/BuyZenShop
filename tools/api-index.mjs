#!/usr/bin/env node
/* Generates docs/API_INDEX.md: for every shared module, its header comment (usage notes) and its export signatures.
 * Run: node tools/api-index.mjs   (the index is what new contributors read instead of opening every file) */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// `node tools/api-index.mjs show ui.js dom.js` prints only the matching sections of the generated index.
if (process.argv[2] === 'show') {
  const text = fs.readFileSync(path.join(ROOT, 'docs/API_INDEX.md'), 'utf8');
  const wanted = process.argv.slice(3);
  const parts = text.split(/^(?=## )/m).filter((x) => x.startsWith('## ') && wanted.some((w) => x.split('\n')[0].includes(w)));
  console.log(parts.join('\n') || 'no matching section');
  process.exit(0);
}
const DIRS = ['js/core', 'js/data', 'js/shared', 'js/admin/lib', 'js/admin/data', 'js/store/lib', 'js/store/components'];
const out = ['# API index (generated by tools/api-index.mjs — do not edit by hand)', '',
  'Header comment + export signatures of every shared module. Open the file itself only when you need the implementation.', ''];

for (const d of DIRS) {
  const dir = path.join(ROOT, d);
  if (!fs.existsSync(dir)) continue;
  for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.js')).sort()) {
    const src = fs.readFileSync(path.join(dir, f), 'utf8');
    const m = /^\s*\/\*([\s\S]*?)\*\//.exec(src);
    const header = m ? m[1].split('\n').map((l) => l.replace(/^\s*\* ?/, '')).join('\n').trim().split('\n').slice(0, 45).join('\n') : '';
    const exps = src.split('\n').filter((l) => /^export\s/.test(l)).map((l) => l.replace(/\s*\{\s*$/, '').slice(0, 170));
    out.push(`## ${d}/${f}`, '', '```', header, '```', '');
    if (exps.length) out.push('```js', ...exps, '```', '');
  }
}
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/API_INDEX.md'), out.join('\n'));
console.log(`docs/API_INDEX.md written (${out.length} lines)`);
