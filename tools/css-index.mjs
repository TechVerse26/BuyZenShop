#!/usr/bin/env node
/* Generates docs/CSS_INDEX.md: CSS custom properties (tokens) and the class names defined in each stylesheet. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['css/tokens.css', 'css/base.css', 'css/components.css', 'css/layout.css', 'css/store.css', 'css/store-chrome.css'];
const out = ['# CSS index (generated by tools/css-index.mjs)', '', 'Tokens are CSS custom properties — never hard-code colours/spacing. Class names below already exist; grep the file for their rules.', ''];
for (const f of FILES) {
  const p = path.join(ROOT, f);
  if (!fs.existsSync(p)) continue;
  const src = fs.readFileSync(p, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  out.push(`## ${f}`, '');
  if (f.endsWith('tokens.css')) {
    const vars = [...new Set([...src.matchAll(/(--[a-z0-9-]+)\s*:/g)].map((m) => m[1]))];
    out.push(vars.join(' '), '');
  } else {
    const cls = [...new Set([...src.matchAll(/\.([a-zA-Z][\w-]*)/g)].map((m) => m[1]))].filter((c) => !/^\d/.test(c));
    out.push(cls.map((c) => '.' + c).join(' '), '');
  }
}
fs.writeFileSync(path.join(ROOT, 'docs/CSS_INDEX.md'), out.join('\n'));
console.log('docs/CSS_INDEX.md written');
